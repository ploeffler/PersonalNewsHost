const {chromium}=require('playwright'),fs=require('fs'),assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'../docs');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1400,height:1050}});
const broadcasts=JSON.parse(fs.readFileSync(root+'/broadcasts.json')).broadcasts;
const latest=broadcasts.at(-1).created_at;
await page.clock.install({time:new Date((latest+180)*1000)});
const updates=[{id:'a'.repeat(24),title:'Beschluss im Parlament bestätigt',text:'Das Parlament hat den Beschluss bestätigt. Weitere Details folgen bei der Quelle.',source:'example.org',url:'https://example.org/a',created_at:latest-600,audio:'short-update-audio/'+'a'.repeat(24)+'.wav'}, {id:'b'.repeat(24),title:'Neue Entwicklung nach der Sendung',text:'Ein weiterer aktueller Bericht liegt vor.',source:'example.org',url:'https://example.org/b',created_at:latest+60}];
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.route('**/*',async route=>{
const url=new URL(route.request().url());
if(url.hostname==='raw.githubusercontent.com')return route.fulfill({body:fs.readFileSync(path.resolve(root,'../assets/logo.png')),contentType:'image/png'});
if(url.hostname!=='playlist.test')return route.abort();
if(url.pathname==='/short-updates.json')return route.fulfill({json:{updates}});
if(/\.(mp4|wav)$/.test(url.pathname))return route.fulfill({status:200,body:Buffer.from([]),contentType:'video/mp4'});
const f=root+(url.pathname==='/'?'/index.html':url.pathname);
if(!fs.existsSync(f))return route.fulfill({status:404,body:'Missing'});
const ext=f.split('.').at(-1);return route.fulfill({body:fs.readFileSync(f),contentType:({html:'text/html',js:'application/javascript',css:'text/css',json:'application/json',vtt:'text/vtt'})[ext]||'text/plain'});
});
await page.goto('https://playlist.test/');await page.waitForSelector('.playlist-button');
assert.equal(await page.locator('.playlist-button').count(),4);
assert.deepEqual(await page.locator('.playlist-label').allTextContents(),['Vorherige Sendung','Kurzupdate','Neueste Sendung','Kurzupdate']);
assert.equal(await page.locator('.playlist-button[aria-current=true]').count(),1);
assert.match(await page.locator('#bulletin-video').getAttribute('src'),new RegExp(broadcasts.at(-1).id));
await page.locator('.playlist-button').first().click();
assert.equal(await page.locator('#bulletin-video').getAttribute('src'),broadcasts[0].video);
assert.equal(await page.locator('#bulletin-transcript').getAttribute('href'),broadcasts[0].transcript);
assert.equal(await page.locator('#bulletin-sources a').count(),broadcasts[0].sources.filter(s=>/^https?:/.test(s.url)).length);
await page.locator('.playlist-button').nth(1).click();
assert.equal(await page.locator('#update-audio').isVisible(),true);
assert.equal(await page.locator('#bulletin-video').isVisible(),false);
assert.match(await page.locator('#update-text').textContent(),/Parlament/);
assert.equal(await page.locator('#bulletin-transcript').isVisible(),false);
await page.locator('.playlist-button').nth(3).click();
assert.equal(await page.locator('#update-audio').isVisible(),false);
assert.equal(await page.locator('#update-text').isVisible(),true);
await page.locator('.playlist-button').nth(2).click();
const player=await page.locator('.broadcast-player').boundingBox(),aside=await page.locator('.broadcast-playlist').boundingBox();assert.ok(aside.x>player.x+player.width);
await page.screenshot({path:'/tmp/pnh-playlist-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:1000});await page.screenshot({path:'/tmp/pnh-playlist-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.ok((await page.locator('.broadcast-playlist').boundingBox()).y>(await page.locator('.broadcast-player').boundingBox()).y);
assert.deepEqual(errors,[]);await browser.close();console.log('Browser playlist: chronological order, video/audio/text switching, sources/subtitles, desktop/mobile: OK');
})().catch(e=>{console.error(e);process.exit(1)});
